// Казахские единицы включаются только при казахском языке распознавания,
// а "мың" и "жүз" безопасны всегда: в русском таких слов нет.
const unitsFor = (kazakh) => (kazakh ? { ...UNITS, ...UNITS_KK } : UNITS)

export const isNumberWord = (w, { kazakh = false } = {}) =>
  w in unitsFor(kazakh) || w in MULTIPLIERS || w in SCALES || w in HALVES || /^\d/.test(w)

// "1500", "1 500", "2,500", "1500.50", "1,5" -> число, либо null
function parseDigits(token) {
  const cleaned = token.replace(/[\s  ]/g, '')

  // "2,500" и "2.500" — это разделитель тысяч, а не дробь: в дробной части
  // не бывает ровно трёх цифр. Распознавание речи часто отдаёт суммы так.
  if (/^\d{1,3}(?:[.,]\d{3})+$/.test(cleaned)) {
    return parseFloat(cleaned.replace(/[.,]/g, ''))
  }

  const decimal = cleaned.replace(',', '.')
  if (!/^\d+(\.\d+)?$/.test(decimal)) return null
  return parseFloat(decimal)
}

/**
 * Читает число, начиная с токена i. Возвращает { value, next } или null.
 * next — индекс первого токена после числа.
 */
export function readNumber(tokens, i, { kazakh = false } = {}) {
  const units = unitsFor(kazakh)
  let total = 0
  let group = 0
  let seen = false
  let pendingHalf = 0
  let j = i

  while (j < tokens.length) {
    const t = tokens[j]

    if (t in HALVES) {
      pendingHalf = HALVES[t]
      seen = true
      j++
      continue
    }

    const digits = parseDigits(t)
    if (digits !== null) {
      // "1500" рядом с уже прочитанным числом — это уже другое число, стоп
      if (seen && !pendingHalf) break
      group += digits
      seen = true
      j++
      continue
    }

    // "500к", "3тыс" — число слиплось с множителем
    const glued = t.match(/^(\d+(?:[.,]\d+)?)(к|k|тыс|тысяч|млн|лям)$/)
    if (glued && !seen) {
      group = parseFloat(glued[1].replace(',', '.'))
      total += group * (MULTIPLIERS[glued[2]] || 1000)
      group = 0
      seen = true
      j++
      continue
    }

    if (t in units) {
      group += units[t]
      seen = true
      j++
      continue
    }

    // "жүз" умножает набранное: "екі жүз" = 200, "жүз мың" = 100 000
    if (t in SCALES) {
      group = (group || 1) * SCALES[t]
      seen = true
      j++
      continue
    }

    if (t in MULTIPLIERS) {
      const base = group + pendingHalf || 1
      total += base * MULTIPLIERS[t]
      group = 0
      pendingHalf = 0
      seen = true
      j++
      continue
    }

    break
  }

  if (!seen) return null
  const value = total + group + pendingHalf
  if (!value && value !== 0) return null
  return { value, next: j }
}
