export const CATEGORY_BY_ID = Object.fromEntries(CATEGORIES.map((c) => [c.id, c]))

export function categoryOf(id) {
  return CATEGORY_BY_ID[id] || CATEGORY_BY_ID.other
}

/** Подбирает категорию по тексту. Выигрывает самое длинное совпавшее слово. */
export function guessCategory(text) {
  const haystack = ' ' + text.toLowerCase().replace(/ё/g, 'е') + ' '
  let best = null
  let bestLen = 0
  for (const cat of CATEGORIES) {
    for (const kw of cat.keywords) {
      const needle = kw.replace(/ё/g, 'е')
      if (haystack.includes(' ' + needle) && needle.length > bestLen) {
        best = cat.id
        bestLen = needle.length
      }
    }
  }
  return best || 'other'
}
